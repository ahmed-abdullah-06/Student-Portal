const DICTS = { en, ur };
export { en, ur };
const STORAGE_KEY = 'novastra-lang';

const I18nContext = createContext(null);

export function I18nProvider({ children }) {
  const [lang, setLangState] = useState(() => localStorage.getItem(STORAGE_KEY) || 'en');

  useEffect(() => {
    const dir = lang === 'ur' ? 'rtl' : 'ltr';
    document.documentElement.lang = lang;
    document.documentElement.dir = dir;
    localStorage.setItem(STORAGE_KEY, lang);
  }, [lang]);

  const value = useMemo(() => {
    const dict = DICTS[lang] || en;
    const t = (key, values = {}) => {
      const template = dict[key] || en[key] || key;
      return Object.entries(values).reduce(
        (text, [name, value]) => text.replace(new RegExp(`\\{${name}\\}`, 'g'), String(value)),
        template,
      );
    };
    const plural = (count, oneKey, otherKey = oneKey) => t(Number(count) === 1 ? oneKey : otherKey, { count });
    return { t, plural, lang, setLang: (next) => setLangState(next === 'ur' ? 'ur' : 'en'), dir: lang === 'ur' ? 'rtl' : 'ltr' };
  }, [lang]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) {
    // Allows isolated page/component tests to render without recreating the app shell.
    return { t: (key) => en[key] || key, plural: (count, oneKey, otherKey = oneKey) => en[Number(count) === 1 ? oneKey : otherKey] || oneKey, lang: 'en', setLang: () => {}, dir: 'ltr' };
  }
  return ctx;
}
